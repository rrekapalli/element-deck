# Create android/upload-keystore.jks + android/key.properties for Play upload signing.
# Usage:
#   .\scripts\create-upload-keystore.ps1
#   .\scripts\create-upload-keystore.ps1 -Force   # overwrite existing (dangerous)
#   .\scripts\create-upload-keystore.ps1 -DName "CN=Element Deck, OU=Mobile, O=Vislesha, C=IN"

[CmdletBinding()]
param(
    [string] $Alias = "upload",
    [string] $DName = "CN=Element Deck, OU=Mobile, O=Vislesha, C=IN",
    [int] $ValidityDays = 10000,
    [switch] $Force,
    [switch] $SkipGcpSecretsAppend,
    # Optional: pass passwords non-interactively (CI). Prefer prompts locally.
    [string] $StorePassword = "",
    [string] $KeyPassword = ""
)

$ErrorActionPreference = "Stop"
$PlaystoreDir = Split-Path -Parent $PSScriptRoot
$Root = (Resolve-Path (Join-Path $PlaystoreDir "..\..\..")).Path
$AndroidDir = Join-Path $Root "android"
$KeystorePath = Join-Path $AndroidDir "upload-keystore.jks"
$PropsPath = Join-Path $AndroidDir "key.properties"
$PrintScript = Join-Path $PSScriptRoot "print-signing-fingerprints.ps1"

if (-not (Get-Command keytool -ErrorAction SilentlyContinue)) {
    throw "keytool not found on PATH. Install JDK 17+ and ensure keytool is available."
}

if ((Test-Path $KeystorePath) -and -not $Force) {
    Write-Host "[OK] Keystore already exists: $KeystorePath" -ForegroundColor Yellow
    Write-Host "     Re-run with -Force to recreate (will break Play if this key was already enrolled)."
} else {
    if ((Test-Path $KeystorePath) -and $Force) {
        Write-Host "[WARN] Overwriting existing keystore at $KeystorePath" -ForegroundColor Yellow
        Remove-Item $KeystorePath -Force
    }

    if (-not $StorePassword) {
        $sec1 = Read-Host "Store password" -AsSecureString
        $sec2 = Read-Host "Confirm store password" -AsSecureString
        $bstr1 = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec1)
        $bstr2 = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec2)
        try {
            $StorePassword = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr1)
            $confirm = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr2)
        } finally {
            [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr1)
            [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr2)
        }
        if ($StorePassword -ne $confirm) { throw "Store passwords do not match." }
        if ($StorePassword.Length -lt 6) { throw "Store password must be at least 6 characters (keytool)." }
    }
    if (-not $KeyPassword) { $KeyPassword = $StorePassword }

    Write-Host "[INFO] Generating $KeystorePath (alias=$Alias, validity=$ValidityDays days)..."
    & keytool -genkeypair -v `
        -keystore $KeystorePath `
        -storetype JKS `
        -keyalg RSA `
        -keysize 2048 `
        -validity $ValidityDays `
        -alias $Alias `
        -storepass $StorePassword `
        -keypass $KeyPassword `
        -dname $DName
    if ($LASTEXITCODE -ne 0) { throw "keytool -genkeypair failed" }
    Write-Host "[OK] Keystore created." -ForegroundColor Green
}

# Resolve passwords for fingerprinting / properties rewrite
if (-not $StorePassword -and (Test-Path $PropsPath)) {
    Get-Content $PropsPath | ForEach-Object {
        if ($_ -match '^\s*storePassword=(.+)$') { $StorePassword = $Matches[1].Trim() }
        if ($_ -match '^\s*keyPassword=(.+)$') { $KeyPassword = $Matches[1].Trim() }
    }
}
if (-not $StorePassword) {
    $sec = Read-Host "Existing keystore store password" -AsSecureString
    $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec)
    try { $StorePassword = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr) }
    finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
}
if (-not $KeyPassword) { $KeyPassword = $StorePassword }

$env:ELEMENT_DECK_KEYSTORE_PASS = $StorePassword
try {
    # Temporary props so print script can read release keystore
    $tmpProps = @"
storePassword=$StorePassword
keyPassword=$KeyPassword
keyAlias=$Alias
storeFile=upload-keystore.jks
msalSignatureHash=
"@
    Set-Content -Path $PropsPath -Value $tmpProps -Encoding utf8

    $lines = @(& $PrintScript -Target release -Quiet)
    $msal = $null; $sha1 = $null; $sha256 = $null
    foreach ($line in $lines) {
        if ($line -match '^MSAL_BASE64=(.+)$') { $msal = $Matches[1] }
        elseif ($line -match '^SHA1=(.+)$') { $sha1 = $Matches[1] }
        elseif ($line -match '^SHA256=(.+)$') { $sha256 = $Matches[1] }
    }
    if (-not $msal) { throw "Failed to compute msalSignatureHash. keytool output: $($lines -join "`n")" }

    $finalProps = @"
# Generated by scripts/create-upload-keystore.ps1 — DO NOT COMMIT
storePassword=$StorePassword
keyPassword=$KeyPassword
keyAlias=$Alias
storeFile=upload-keystore.jks
msalSignatureHash=$msal
"@
    Set-Content -Path $PropsPath -Value $finalProps -Encoding utf8
    Write-Host "[OK] Wrote $PropsPath (msalSignatureHash set)." -ForegroundColor Green

    if (-not $SkipGcpSecretsAppend) {
        $gcp = Join-Path $Root "GCP_Secrets.md"
        $block = @"

## Release / upload signing certificate

| Fingerprint | Value |
| --- | --- |
| Alias | ``$Alias`` |
| SHA-1 | ``$sha1`` |
| SHA-256 | ``$sha256`` |
| MSAL Base64 | ``$msal`` |
| Keystore | ``android/upload-keystore.jks`` (gitignored) |
| Generated | $(Get-Date -Format "yyyy-MM-dd") |

"@
        if (Test-Path $gcp) {
            $existing = Get-Content $gcp -Raw
            if ($existing -match "## Release / upload signing certificate") {
                # Replace TBD section if present
                $updated = [regex]::Replace(
                    $existing,
                    "(?s)## Release / upload signing certificate.*?(?=## Notes|\z)",
                    $block.Trim() + "`r`n`r`n"
                )
                Set-Content -Path $gcp -Value $updated -Encoding utf8
            } else {
                Add-Content -Path $gcp -Value $block -Encoding utf8
            }
            Write-Host "[OK] Updated GCP_Secrets.md release section." -ForegroundColor Green
        } else {
            Write-Host "[INFO] GCP_Secrets.md not found; skip append. Fingerprints printed above."
        }
    }
} finally {
    Remove-Item Env:ELEMENT_DECK_KEYSTORE_PASS -ErrorAction SilentlyContinue
}

Write-Host ""
Write-Host "Next:" -ForegroundColor Cyan
Write-Host "  1. Back up android/upload-keystore.jks + passwords offline."
Write-Host "  2. Paste SHA-1 into the Firebase / Google Cloud Android OAuth client (package com.vislesha.element_deck)."
Write-Host "  3. After the first Play upload, also add the Play App Signing SHA-1 in Firebase."
Write-Host "  4. Build: .\deployment\android\playstore\scripts\build-release-aab.ps1"
Write-Host "  See Docs/play-store.md"
