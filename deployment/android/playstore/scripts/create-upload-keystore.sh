#!/usr/bin/env bash
# Create android/upload-keystore.jks + android/key.properties.
# Usage:
#   ./scripts/create-upload-keystore.sh
#   ./scripts/create-upload-keystore.sh --force
# Env:
#   STORE_PASSWORD / KEY_PASSWORD — optional non-interactive

set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
ANDROID="$ROOT/android"
KEYSTORE="$ANDROID/upload-keystore.jks"
PROPS="$ANDROID/key.properties"
ALIAS="${ALIAS:-upload}"
DNAME="${DNAME:-CN=Element Deck, OU=Mobile, O=Vislesha, C=IN}"
VALIDITY="${VALIDITY:-10000}"
FORCE=false

for arg in "$@"; do
  case "$arg" in
    --force|-f) FORCE=true ;;
    -h|--help)
      sed -n '2,8p' "$0"
      exit 0
      ;;
  esac
done

command -v keytool >/dev/null || { echo "keytool not on PATH" >&2; exit 1; }

if [[ -f "$KEYSTORE" && "$FORCE" != true ]]; then
  echo "[OK] Keystore already exists: $KEYSTORE"
  echo "     Pass --force to recreate (dangerous if already on Play)."
else
  if [[ -f "$KEYSTORE" && "$FORCE" == true ]]; then
    echo "[WARN] Overwriting $KEYSTORE"
    rm -f "$KEYSTORE"
  fi
  if [[ -z "${STORE_PASSWORD:-}" ]]; then
    read -r -s -p "Store password: " STORE_PASSWORD; echo
    read -r -s -p "Confirm store password: " CONFIRM; echo
    [[ "$STORE_PASSWORD" == "$CONFIRM" ]] || { echo "Passwords do not match" >&2; exit 1; }
  fi
  KEY_PASSWORD="${KEY_PASSWORD:-$STORE_PASSWORD}"
  echo "[INFO] Generating $KEYSTORE ..."
  keytool -genkeypair -v \
    -keystore "$KEYSTORE" \
    -storetype JKS \
    -keyalg RSA \
    -keysize 2048 \
    -validity "$VALIDITY" \
    -alias "$ALIAS" \
    -storepass "$STORE_PASSWORD" \
    -keypass "$KEY_PASSWORD" \
    -dname "$DNAME"
fi

if [[ -z "${STORE_PASSWORD:-}" && -f "$PROPS" ]]; then
  STORE_PASSWORD="$(sed -n 's/^storePassword=//p' "$PROPS" | head -1 | tr -d '\r')"
  KEY_PASSWORD="$(sed -n 's/^keyPassword=//p' "$PROPS" | head -1 | tr -d '\r')"
fi
if [[ -z "${STORE_PASSWORD:-}" ]]; then
  read -r -s -p "Existing keystore store password: " STORE_PASSWORD; echo
fi
KEY_PASSWORD="${KEY_PASSWORD:-$STORE_PASSWORD}"

cat >"$PROPS" <<EOF
# Generated by scripts/create-upload-keystore.sh — DO NOT COMMIT
storePassword=$STORE_PASSWORD
keyPassword=$KEY_PASSWORD
keyAlias=$ALIAS
storeFile=upload-keystore.jks
msalSignatureHash=
EOF

mapfile -t LINES < <("$(dirname "${BASH_SOURCE[0]}")/print-signing-fingerprints.sh" release | tee /dev/stderr)
MSAL=""; SHA1=""; SHA256=""
for line in "${LINES[@]}"; do
  case "$line" in
    MSAL_BASE64=*) MSAL="${line#MSAL_BASE64=}" ;;
    SHA1=*) SHA1="${line#SHA1=}" ;;
    SHA256=*) SHA256="${line#SHA256=}" ;;
  esac
done
[[ -n "$MSAL" ]] || { echo "Failed to compute MSAL hash" >&2; exit 1; }

cat >"$PROPS" <<EOF
# Generated by scripts/create-upload-keystore.sh — DO NOT COMMIT
storePassword=$STORE_PASSWORD
keyPassword=$KEY_PASSWORD
keyAlias=$ALIAS
storeFile=upload-keystore.jks
msalSignatureHash=$MSAL
EOF

echo "[OK] Wrote $PROPS"

GCP="$ROOT/GCP_Secrets.md"
if [[ -f "$GCP" ]]; then
  {
    echo ""
    echo "## Release / upload signing certificate"
    echo ""
    echo "| Fingerprint | Value |"
    echo "| --- | --- |"
    echo "| Alias | \`$ALIAS\` |"
    echo "| SHA-1 | \`$SHA1\` |"
    echo "| SHA-256 | \`$SHA256\` |"
    echo "| MSAL Base64 | \`$MSAL\` |"
    echo "| Keystore | \`android/upload-keystore.jks\` (gitignored) |"
    echo "| Generated | $(date +%Y-%m-%d) |"
    echo ""
  } >>"$GCP"
  echo "[OK] Appended release fingerprints to GCP_Secrets.md (review for duplicates)."
fi

echo ""
echo "Next: paste SHA-1 into the Firebase Android OAuth client (com.vislesha.element_deck), then build-release-aab.sh"
echo "Docs: Docs/play-store.md"
